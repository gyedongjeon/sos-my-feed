/** The feeds in a language about any of the interests, in the catalog's order; with no
 * interests, every feed in the language. */
export function recommend(language: PageLanguage, interests: readonly Topic[]): CatalogFeed[] {
  return CATALOG.filter(
    (feed) => feed.language === language && (!interests.length || feed.topics.some((topic) => interests.includes(topic))),
  )
}
